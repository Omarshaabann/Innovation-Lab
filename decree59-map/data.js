function _jit(name, base) {
  let h = 0; for (const c of name) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  const a = ((h % 1000) / 1000 - 0.5) * 0.09, b = (((h >> 10) % 1000) / 1000 - 0.5) * 0.09;
  return [base[0] + a, base[1] + b];
}

function resolvePlace(place, district, gov) {
  if (place && PLACES[place]) return { ll: PLACES[place], approx: false };
  if (district && DISTRICTS[district]) return { ll: _jit(place || district, DISTRICTS[district]), approx: true };
  if (place && place.includes(' – ')) {
    const first = place.split(' – ')[0].trim();
    if (PLACES[first]) return { ll: _jit(place, PLACES[first]), approx: true };
  }
  return null;
}

